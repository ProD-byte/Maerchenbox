// Binaere Suche; unbekannte Texte kommen unveraendert zurueck
const char *aufEnglisch(const char *de) {
  int a = 0, b = (int)(sizeof PAARE / sizeof PAARE[0]) - 1;
  while (a <= b) {
    int m = (a + b) / 2, v = strcmp(de, PAARE[m].de);
    if (v == 0) return PAARE[m].en;
    if (v < 0) b = m - 1; else a = m + 1;
  }
  return de;
}
